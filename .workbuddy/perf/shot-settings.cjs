const http=require('http'),fs=require('fs')
const sleep=ms=>new Promise(r=>setTimeout(r,ms))
const j=u=>new Promise((res,rej)=>http.get(u,r=>{let b='';r.on('data',c=>b+=c);r.on('end',()=>res(JSON.parse(b)))}).on('error',rej))
;(async()=>{
  const list=await j('http://127.0.0.1:9222/json/list')
  const page=list.find(t=>t.type==='page')
  const ws=new WebSocket(page.webSocketDebuggerUrl)
  await new Promise((r,x)=>{ws.addEventListener('open',r);ws.addEventListener('error',x)})
  let id=0;const p=new Map()
  ws.addEventListener('message',e=>{const m=JSON.parse(e.data);if(m.id&&p.has(m.id)){p.get(m.id)(m.result||m.error);p.delete(m.id)}})
  const send=(m,q={})=>new Promise(r=>{const i=++id;p.set(i,r);ws.send(JSON.stringify({id:i,method:m,params:q}))})
  await send('Page.enable');await send('Runtime.enable')
  await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:3,mobile:true})
  await send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5})
  await send('Page.navigate',{url:'http://127.0.0.1:8124/site/index.html'})
  await sleep(4000)
  async function tap(x,y){await send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y,id:1}]});await sleep(50);await send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await sleep(400)}
  await tap(195,720)
  await sleep(1200)
  const s=await send('Page.captureScreenshot',{format:'png'})
  fs.writeFileSync(__dirname+'/settings2.png',Buffer.from(s.data,'base64'))
  console.log('ok')
  process.exit(0)
})()
